import { isNoteImage } from './note-document.js';

const types = new Set(['rectangle', 'diamond', 'ellipse', 'line', 'arrow', 'freedraw', 'text', 'image', 'frame', 'magicframe', 'embeddable', 'iframe']);
const record = value => !!value && typeof value === 'object' && !Array.isArray(value);
const safeId = value => typeof value === 'string' && /^[\w-]{1,128}$/.test(value) && !['__proto__', 'constructor', 'prototype'].includes(value);
const canonical = value => JSON.stringify(value, (_key, item) => record(item) ? Object.fromEntries(Object.keys(item).sort().map(key => [key, item[key]])) : item);
export const emptyBoard = () => ({ version: 1, elements: [], files: {} });

// Only portable scene data belongs in the notebook. Camera, selection and history are local.
export function boardScene(elements, files) {
  const ids = new Set(elements.filter(element => element.type === 'image').map(element => element.fileId));
  return { version: 1, elements: structuredClone(elements), files: Object.fromEntries(Object.entries(files).filter(([id]) => ids.has(id)).map(([id, file]) => [id, { id, dataURL: file.dataURL, mimeType: file.mimeType, created: file.created }])) };
}

// Imports/clear may omit old objects. Keep deletion tombstones so another editor cannot
// accidentally resurrect them, and retain their images for local undo and recovery.
export function boardChange(previous, elements, files) {
  const present = new Set(elements.map(element => element.id));
  const removed = previous.elements.filter(element => !present.has(element.id)).map(element => element.isDeleted ? element : { ...element, isDeleted: true, version: element.version + 1, versionNonce: 0 });
  return boardScene([...elements, ...removed], { ...previous.files, ...files });
}

export function validBoard(board) {
  if (!record(board) || board.version !== 1 || !Array.isArray(board.elements) || board.elements.length > 10000 || !record(board.files) || Object.keys(board.files).length > 1000) return false;
  const ids = new Set();
  for (const element of board.elements) {
    if (!record(element) || !safeId(element.id) || ids.has(element.id) || !types.has(element.type) || !Number.isSafeInteger(element.version) || element.version < 1 || !Number.isSafeInteger(element.versionNonce) || typeof element.isDeleted !== 'boolean' || !['x', 'y', 'width', 'height', 'angle'].every(key => Number.isFinite(element[key]))) return false;
    if (element.type === 'image' && element.fileId !== null && element.fileId !== undefined && (!safeId(element.fileId) || (!element.isDeleted && element.status === 'saved' && !Object.hasOwn(board.files, element.fileId)))) return false;
    ids.add(element.id);
  }
  return Object.entries(board.files).every(([id, file]) => safeId(id) && record(file) && file.id === id && isNoteImage(file.dataURL) && file.dataURL.startsWith(`data:${file.mimeType};base64,`) && Number.isFinite(file.created));
}

// Whole elements are the unit of collaboration: never combine a shape's geometry field by field.
// Versions also cover undo/redo and deletion tombstones. Equal versions use a stable tie-break.
export function mergeBoards(local, remote) {
  const elements = new Map(local.elements.map(element => [element.id, element]));
  for (const other of remote.elements) {
    const mine = elements.get(other.id);
    if (!mine || other.version > mine.version || (other.version === mine.version && (other.versionNonce < mine.versionNonce || (other.versionNonce === mine.versionNonce && canonical(other) < canonical(mine))))) elements.set(other.id, other);
  }
  const ordered = [...elements.values()].sort((a, b) => {
    const first = a.index || '', second = b.index || '';
    return first < second ? -1 : first > second ? 1 : a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
  });
  // File IDs are content hashes generated by Excalidraw; bytes are immutable.
  const files = Object.fromEntries([...new Set([...Object.keys(local.files), ...Object.keys(remote.files)])].sort().map(id => {
    const mine = local.files[id], other = remote.files[id];
    return [id, !mine ? other : !other ? mine : canonical(mine) <= canonical(other) ? mine : other];
  }));
  return boardScene(ordered, files);
}

export function boardText(board) {
  return board.elements.filter(element => !element.isDeleted && element.type === 'text').map(element => element.text || '').join('\n');
}
