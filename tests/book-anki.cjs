// Reader/Anki integration with real editors and temporary files; no personal data or network.
const { _electron: electron } = require('playwright');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..'), directory = fs.mkdtempSync(path.join(os.tmpdir(), 'organon-book-anki-'));
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
let app;
(async () => {
  const { seed, firstPlan } = await import('../src/model.js');
  const { basicModel, reversedModel } = await import('../src/anki.js');
  const { BookFiles } = require('../electron/books.cjs');
  const store = new BookFiles(directory), first = firstPlan(), second = firstPlan();
  first.name = 'Plano do livro'; second.name = 'Plano com alternativas';
  const data = { ...seed(), onboardingCompleted: true, plans: [first, second] };
  for (const [index, title, planIds] of [[0, 'Leitura vinculada', [first.id]], [1, 'Leitura independente', []], [2, 'Leitura com alternativas', [second.id]]]) {
    const file = path.join(directory, title + '.pdf');
    fs.writeFileSync(file, Buffer.concat([fs.readFileSync(path.join(root, 'tests/fixtures/reading.pdf')), Buffer.from(`\n% Synthetic ${index}\n`)]));
    const book = store.import(file); data.books.push({ ...book, title, planIds, ...(index === 0 ? { page: 2 } : {}) });
  }
  const epub = store.import(path.join(root, 'tests/fixtures/reading.epub'));
  data.books.push({ ...epub, title: 'Leitura EPUB', planIds: [first.id] });
  data.anki.models = [basicModel, reversedModel];
  data.anki.decks = [{ id: 'linked', name: 'Baralho vinculado', presetId: 'default', planIds: [first.id] }, { id: 'choice-one', name: 'Primeira alternativa', presetId: 'default', planIds: [second.id] }, { id: 'choice-two', name: 'Segunda alternativa', presetId: 'default', planIds: [second.id] }];
  fs.writeFileSync(path.join(directory, 'compasso.json'), JSON.stringify(data));
  app = await electron.launch({ args: [root, `--user-data-dir=${directory}`, '--skip-account-prompt'], env });
  const page = await app.firstWindow(); page.setDefaultTimeout(20000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const reader = page.getByRole('dialog', { name: /^Lendo / });
  const card = page.getByRole('dialog', { name: 'Criar carta', exact: true });
  const front = () => card.getByRole('textbox', { name: 'Frente', exact: true });
  const back = () => card.getByRole('textbox', { name: 'Verso', exact: true });
  async function openBook(title) {
    await page.locator('.sidebar nav').getByRole('button', { name: 'Livros', exact: true }).click();
    await page.getByRole('button', { name: `Ler ${title}`, exact: true }).click();
    await reader.waitFor();
  }
  async function openMainCard() {
    await page.locator('.sidebar nav').getByRole('button', { name: 'Anki', exact: true }).click();
    await page.getByRole('button', { name: 'Adicionar', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Criar carta', exact: true }).click();
    await front().waitFor();
  }
  async function outside() { await page.locator('.modal-backdrop').last().click({ position: { x: 4, y: 4 } }); await card.waitFor({ state: 'hidden' }); }
  await openBook('Leitura vinculada');
  await reader.getByRole('document', { name: 'Página 2', exact: true }).waitFor();
  await reader.getByLabel('Zoom do PDF', { exact: true }).selectOption('1.5');
  await reader.evaluate(element => { element.dataset.readerTest = 'same-reader'; });
  await reader.getByRole('button', { name: 'Anotar no Anki', exact: true }).click();
  await front().waitFor();
  assert.equal(await card.getByLabel('Baralho', { exact: true }).inputValue(), 'linked');
  await card.getByLabel('Tipo de nota', { exact: true }).selectOption(reversedModel.id);
  await front().fill('Questão do livro'); await back().fill('Resposta do livro');
  await card.getByLabel('Marcadores', { exact: true }).fill('leitura teste');
  const png = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = canvas.height = 2; canvas.getContext('2d').fillRect(0, 0, 2, 2); return canvas.toDataURL('image/png').split(',')[1]; });
  await card.getByLabel('Adicionar mídia a Frente', { exact: true }).setInputFiles({ name: 'synthetic.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await front().getByRole('img', { name: 'Imagem da carta', exact: true }).waitFor();
  await outside();
  assert.equal(await reader.getByLabel('Ir para página', { exact: true }).inputValue(), '2');
  await reader.getByRole('button', { name: 'Anotar no Anki', exact: true }).click();
  await front().getByRole('img', { name: 'Imagem da carta', exact: true }).waitFor();
  assert.match(await front().innerText(), /Questão do livro/);
  assert.equal(await card.getByLabel('Marcadores', { exact: true }).inputValue(), 'leitura teste');
  assert.equal(await card.getByLabel('Tipo de nota', { exact: true }).inputValue(), reversedModel.id);
  await page.keyboard.press('Escape'); await card.waitFor({ state: 'hidden' }); await reader.waitFor();
  await reader.getByRole('button', { name: 'Anotar no Anki', exact: true }).click();
  await front().getByRole('img', { name: 'Imagem da carta', exact: true }).waitFor();
  const spacing = await card.evaluate(element => {
    const actions = element.querySelector('.anki-editor > .modal-actions');
    element.style.maxHeight = '250px';
    element.scrollTop = element.scrollHeight;
    const above = parseFloat(getComputedStyle(actions).paddingTop);
    const visibleBottom = element.getBoundingClientRect().top + element.clientTop + element.clientHeight;
    const below = visibleBottom - actions.getBoundingClientRect().bottom;
    const scrolled = element.scrollTop > 0;
    element.style.removeProperty('max-height');
    return { above, below, scrolled };
  });
  assert.ok(spacing.scrolled && spacing.above > 0 && Math.abs(spacing.above - spacing.below) <= 1, 'O espaço inferior precisa continuar visível no fim da rolagem.');
  await card.getByRole('button', { name: 'Criar carta', exact: true }).click(); await card.waitFor({ state: 'hidden' });
  assert.equal(await reader.getAttribute('data-reader-test'), 'same-reader');
  assert.equal(await reader.getByLabel('Zoom do PDF', { exact: true }).inputValue(), '1.5');
  await page.waitForFunction(async () => (await window.desktop.load()).anki.notes.length === 1);
  const saved = await page.evaluate(() => window.desktop.load());
  assert.equal(saved.anki.cards.length, 2); assert(saved.anki.cards.every(c => c.deckId === 'linked'));
  assert.match(saved.anki.notes[0].fields[0], /<img/); assert.equal(Object.keys(saved.anki.media).length, 1);
  await reader.getByRole('button', { name: 'Fechar leitor', exact: true }).click();
  await openMainCard();
  await card.getByLabel('Baralho', { exact: true }).selectOption('choice-one');
  await front().fill('Rascunho principal'); await back().fill('Verso principal');
  await card.getByLabel('Marcadores', { exact: true }).fill('rascunho');
  await outside();
  await page.locator('.sidebar nav').getByRole('button', { name: /^Meu dia\s*\d*$/ }).click();
  await openMainCard(); assert.match(await front().innerText(), /Rascunho principal/);
  assert.equal(await card.getByLabel('Baralho', { exact: true }).inputValue(), 'choice-one');
  await card.getByRole('button', { name: 'Limpar', exact: true }).click();
  assert.equal((await front().innerText()).trim(), ''); assert.equal((await back().innerText()).trim(), '');
  assert.equal(await card.getByLabel('Marcadores', { exact: true }).inputValue(), '');
  assert.equal(await card.getByLabel('Baralho', { exact: true }).inputValue(), 'choice-one');
  await front().fill('Descartar pelo X'); await card.getByRole('button', { name: 'Fechar', exact: true }).click();
  await openMainCard(); assert.equal((await front().innerText()).trim(), '');
  await card.getByRole('button', { name: 'Fechar', exact: true }).click();
  await openBook('Leitura independente'); await reader.getByRole('button', { name: 'Anotar no Anki', exact: true }).click();
  const pick = page.getByRole('dialog', { name: 'Anotar no Anki', exact: true });
  await pick.getByRole('button', { name: 'Criar baralho', exact: true }).click();
  const deck = page.getByRole('dialog', { name: 'Criar baralho', exact: true });
  await deck.getByLabel('Nome', { exact: true }).fill('Criado durante a leitura');
  await deck.getByRole('button', { name: 'Criar baralho', exact: true }).click();
  await front().fill('Carta do livro independente');
  await card.getByRole('button', { name: 'Criar carta', exact: true }).click(); await card.waitFor({ state: 'hidden' });
  await reader.getByRole('button', { name: 'Fechar leitor', exact: true }).click();
  await openBook('Leitura com alternativas'); await reader.getByRole('button', { name: 'Anotar no Anki', exact: true }).click();
  await pick.waitFor(); assert.equal(await pick.getByLabel('Baralho', { exact: true }).inputValue(), '');
  await pick.getByLabel('Baralho', { exact: true }).selectOption('choice-two');
  await pick.getByRole('button', { name: 'Continuar', exact: true }).click(); await front().waitFor();
  assert.equal(await card.getByLabel('Baralho', { exact: true }).inputValue(), 'choice-two');
  await card.getByRole('button', { name: 'Fechar', exact: true }).click();
  await reader.getByRole('button', { name: 'Fechar leitor', exact: true }).click();
  await openBook('Leitura EPUB'); await page.waitForFunction(() => !document.querySelector('.ebook-message'));
  await reader.getByLabel('Tamanho da fonte', { exact: true }).selectOption('24');
  await reader.getByRole('button', { name: 'Anotar no Anki', exact: true }).click(); await front().waitFor();
  assert.equal(await card.getByLabel('Baralho', { exact: true }).inputValue(), 'linked');
  await page.keyboard.press('Escape'); await card.waitFor({ state: 'hidden' });
  assert.equal(await reader.getByLabel('Tamanho da fonte', { exact: true }).inputValue(), '24');
  assert.deepEqual(errors, []);
  console.log('Leitor PDF/EPUB com Anki por planos, seleção/criação de baralho, leitura preservada, rascunho com mídia, Limpar e espaçamento das ações aprovados. Perfil temporário; sem dados pessoais.');
})().catch(error => { console.error(error.stack || error.message); process.exitCode = 1; }).finally(async () => {
  if (app) await app.close();
  const target = path.resolve(directory);
  if (path.dirname(target) === path.resolve(os.tmpdir()) && path.basename(target).startsWith('organon-book-anki-')) fs.rmSync(target, { recursive: true, force: true });
});
