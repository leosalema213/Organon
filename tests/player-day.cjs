const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'organon-player-day-'));
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
let app;
(async () => {
  const { dayKey, firstPlan, pause, play, seed } = await import('../src/model.js');
  const today = dayKey(), previous = new Date(`${today}T12:00:00`); previous.setDate(previous.getDate() - 1);
  const yesterday = dayKey(previous), oldNow = previous.getTime();
  const plan = { ...firstPlan(), days: [0,1,2,3,4,5,6] };
  plan.blocks[0].minutes = 1; plan.blocks[2].minutes = 1;
  const initial = { ...seed(), plans: [plan], onboardingCompleted: true };
  initial.settings.sound = false;
  const saved = pause(play(initial, plan, plan.blocks[1], yesterday, oldNow - 120000), oldNow);
  fs.writeFileSync(path.join(profile, 'compasso.json'), JSON.stringify(saved));
  app = await electron.launch({ args: [root, `--user-data-dir=${profile}`, '--skip-account-prompt'], env });
  const page = await app.firstWindow(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('heading', { name: 'Meu dia', exact: true }).waitFor();
  await page.locator('.bottom-player .player-info strong').getByText(plan.blocks[0].name, { exact: true }).waitFor();
  await page.waitForFunction(async today => (await window.desktop.load()).active?.date === today, today);
  let current = await page.evaluate(() => window.desktop.load());
  assert.deepEqual(current.records, saved.records);
  assert.equal(current.active.running, false);
  await page.clock.install({ time: new Date(`${today}T23:59:50`) });
  await page.clock.fastForward(20000);
  const tomorrow = new Date(`${today}T12:00:00`); tomorrow.setDate(tomorrow.getDate() + 1);
  const nextDay = dayKey(tomorrow);
  await page.waitForFunction(async day => (await window.desktop.load()).active?.date === day, nextDay);
  current = await page.evaluate(() => window.desktop.load());
  assert.equal(current.active.running, false);
  assert.equal(current.active.blockId, plan.blocks[0].id);
  assert.deepEqual(current.records, saved.records);
  await page.clock.setSystemTime(new Date(`${nextDay}T23:59:50`));
  // Clock jumps may preserve a historical calendar selection; explicitly start on the simulated day.
  await page.getByTitle('Voltar para hoje', { exact: true }).click();
  await page.getByRole('button', { name: `Iniciar ${plan.blocks[2].name}`, exact: true }).click();
  await page.waitForFunction(async day => { const state = await window.desktop.load(); return state.active?.date === day && state.active.running; }, nextDay);
  await page.clock.fastForward(20000);
  assert.equal(await page.locator('.bottom-player .player-info strong').innerText(), plan.blocks[2].name);
  assert.equal(await page.locator('.bottom-player').getByRole('button', { name: 'Pausar aula', exact: true }).count(), 1);
  await page.clock.fastForward(45000);
  const following = new Date(tomorrow); following.setDate(following.getDate() + 1);
  const followingDay = dayKey(following);
  await page.locator('.bottom-player .player-info strong').getByText(plan.blocks[0].name, { exact: true }).waitFor();
  await page.waitForFunction(async ({ day, blockId }) => { const state = await window.desktop.load(); return state.active?.date === day && state.active.blockId === blockId && !state.active.running; }, { day: followingDay, blockId: plan.blocks[0].id });
  current = await page.evaluate(() => window.desktop.load());
  assert.equal(current.active.blockId, plan.blocks[0].id, JSON.stringify({ active: current.active, blocks: plan.blocks.map(block => ({ id: block.id, name: block.name })), records: current.records }));
  assert.equal(current.active.running, false);
  assert.equal(current.records[`${nextDay}|${plan.id}|${plan.blocks[2].id}`].done, true, JSON.stringify({ today, nextDay, followingDay, active: current.active, records: current.records }));
  assert.equal(current.records[`${followingDay}|${plan.id}|${plan.blocks[2].id}`].done, false);
  assert.deepEqual(errors, []);
  console.log('PASS: reopening selects today without changing history; paused midnight switches immediately; running lesson finishes before selecting the new day paused.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (app) await app.close(); });
