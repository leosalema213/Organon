const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'organon-note-alarms-'));
const file = path.join(profile, 'compasso.json');
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
let app;
(async () => {
  const { seed, validateData } = await import('../src/model.js');
  fs.writeFileSync(file, JSON.stringify({ ...seed(), onboardingCompleted: true }));
  app = await electron.launch({ args: [root, `--user-data-dir=${profile}`, '--skip-account-prompt'], env });
  const page = await app.firstWindow(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('heading', { name: 'Meu dia', exact: true }).waitFor();
  await page.clock.install({ time: new Date('2026-11-09T13:00:00') });
  await page.getByRole('button', { name: 'Notas', exact: true }).click();
  const controls = page.locator('.reminder-view-controls');
  for (const name of ['Período anterior', 'Próximo período']) {
    const arrow = controls.getByRole('button', { name, exact: true });
    assert.equal(await arrow.locator('svg').count(), 1);
    assert.equal((await arrow.innerText()).trim(), '');
  }
  const heights = await controls.locator('input, button').evaluateAll(items => items.map(item => item.getBoundingClientRect().height));
  assert(Math.max(...heights) - Math.min(...heights) < 1, `Alturas desalinhadas: ${heights}`);
  assert.equal(await controls.locator('label').count(), 0);
  await page.getByRole('button', { name: 'Nova nota', exact: true }).click();
  let modal = page.getByRole('dialog', { name: 'Nova nota', exact: true });
  const columns = await modal.locator('.reminder-datetime label').evaluateAll(items => items.map(item => { const rect = item.getBoundingClientRect(); return { top: rect.top, width: rect.width }; }));
  assert.equal(columns.length, 2); assert(Math.abs(columns[0].top - columns[1].top) < 1); assert(Math.abs(columns[0].width - columns[1].width) < 1);
  assert.equal(await modal.getByText(/A última escolha de som/).count(), 0);
  await modal.getByLabel('Título da nota', { exact: true }).fill('Verificar o arroz');
  await modal.getByRole('button', { name: 'Daqui a 10 minutos', exact: true }).click();
  assert.equal(await modal.getByLabel('Horário da nota', { exact: true }).inputValue(), '13:10');
  await modal.getByLabel('Uso único', { exact: true }).check();
  await modal.getByLabel('Som do lembrete', { exact: true }).selectOption('rise');
  await modal.getByRole('button', { name: 'Salvar nota', exact: true }).click();
  await page.getByRole('button', { name: 'Nova nota', exact: true }).click();
  modal = page.getByRole('dialog', { name: 'Nova nota', exact: true });
  assert.equal(await modal.getByLabel('Som do lembrete', { exact: true }).inputValue(), 'rise');
  await modal.getByLabel('Título da nota', { exact: true }).fill('Nota permanente');
  await modal.getByRole('button', { name: 'Daqui a 1 hora', exact: true }).click();
  await modal.getByRole('button', { name: 'Salvar nota', exact: true }).click();
  await page.getByRole('button', { name: 'Semana', exact: true }).click();
  assert.equal(await page.locator('.reminder-agenda-day').count(), 7);
  await page.getByRole('button', { name: 'Mês', exact: true }).click();
  assert.equal(await page.locator('.reminder-agenda-day').count(), 30);
  await page.getByRole('button', { name: 'Dia', exact: true }).click();
  await page.getByLabel('Data da agenda', { exact: true }).fill('2026-11-09');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].minimize());
  await page.clock.fastForward(10 * 60000);
  const alarm = page.getByRole('dialog', { name: 'Lembrete', exact: true });
  await alarm.waitFor();
  assert.equal(await alarm.getByRole('heading', { name: 'Verificar o arroz', exact: true }).count(), 1);
  await alarm.getByRole('button', { name: 'Dispensar', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Editar nota Verificar o arroz', exact: true }).count(), 0);
  await page.clock.fastForward(50 * 60000);
  await alarm.waitFor();
  await alarm.getByRole('button', { name: 'Dispensar', exact: true }).click();
  await page.clock.fastForward(5000);
  assert.equal(await alarm.count(), 0);
  await page.waitForFunction(async () => (await window.desktop.load()).reminders.length === 1);
  const saved = validateData(JSON.parse(fs.readFileSync(file, 'utf8')));
  assert.equal(saved.settings.reminderSound, 'rise');
  assert.equal(saved.reminders[0].title, 'Nota permanente');
  assert.deepEqual(saved.reminders[0].notifiedDates, ['2026-11-09']);
  assert.deepEqual(errors, []);
  await app.close(); app = null;
  app = await electron.launch({ args: [root, `--user-data-dir=${profile}`, '--skip-account-prompt'], env });
  const reopened = await app.firstWindow();
  await reopened.getByRole('heading', { name: 'Meu dia', exact: true }).waitFor();
  await reopened.clock.install({ time: new Date('2026-11-09T14:05:00') });
  await reopened.clock.fastForward(3000);
  assert.equal(await reopened.getByRole('dialog', { name: 'Lembrete', exact: true }).count(), 0);
  console.log('PASS: scheduling, single-use deletion, remembered sound, day/week/month agenda, minimized alarms, persistence and no replay after restart. Native Windows delivery and audible output require manual validation.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (app) await app.close(); });
