// Cold Portuguese checker + gradual canvas typing, with synthetic data only.
const { _electron: electron } = require('playwright');
const { drawRectangle, clickCanvas, canvasPoint } = require('./board-gestures.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'organon-board-spelling-'));
const reportFile = path.join(root, 'test-output', 'board-spelling.json');
const report = { crashes: [], errors: [], phases: [] };
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
let app;
(async () => {
  const { seed, newNotebook, newPage } = await import('../src/model.js');
  const book = newNotebook(); book.name = 'Regressão ortográfica'; book.pages = [newPage('board')];
  const file = path.join(profile, 'compasso.json');
  fs.writeFileSync(file, JSON.stringify({ ...seed(), onboardingCompleted: true, notebooks: [book] }));
  app = await electron.launch({ args: [root, `--user-data-dir=${profile}`, '--skip-account-prompt'], env });
  const page = await app.firstWindow(); page.setDefaultTimeout(15000);
  page.on('pageerror', error => report.errors.push(error.message));
  page.on('crash', () => report.crashes.push('Renderer crashed'));
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.session.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_details, callback) => callback({ cancel: true })));
  await page.getByRole('button', { name: 'Cadernos', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir caderno Regressão ortográfica', exact: true }).click();
  await page.locator('.notebook-board .excalidraw__canvas.interactive').waitFor();
  await drawRectangle(page, 300, 170, 90, 60);
  await drawRectangle(page, 470, 170, 90, 60);
  await page.locator('[data-testid="toolbar-arrow"]').check({ force: true });
  const arrow = await canvasPoint(page, 390, 250, 80, 30);
  await page.mouse.move(arrow.x, arrow.y); await page.mouse.down();
  await page.mouse.move(arrow.x + 80, arrow.y + 30, { steps: 10 }); await page.mouse.up();
  report.phases.push('two rectangles and arrow');
  await page.locator('[data-testid="toolbar-text"]').check({ force: true });
  await clickCanvas(page, 400, 330);
  await page.keyboard.type('Texto gradual para verificar o corretor ', { delay: 80 });
  await page.keyboard.insertText('coração e ação');
  await page.keyboard.press('Escape');
  report.phases.push('gradual text');
  const text = 'Texto gradual para verificar o corretor coração e ação';
  await page.waitForFunction(async text => (await window.desktop.load()).notebooks[0].pages[0].text.includes(text), text);
  const snapshot = JSON.parse(fs.readFileSync(file, 'utf8'));
  const elements = snapshot.notebooks[0].pages[0].board.elements.filter(e => !e.isDeleted);
  assert.equal(elements.filter(e => e.type === 'rectangle').length, 2);
  assert.equal(elements.filter(e => e.type === 'arrow').length, 1);
  assert(elements.some(e => e.type === 'text' && e.text === text));
  await page.reload();
  await page.getByRole('button', { name: 'Cadernos', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir caderno Regressão ortográfica', exact: true }).click();
  await page.locator('.notebook-board .excalidraw__canvas.interactive').waitFor();
  assert.equal((await page.evaluate(() => window.desktop.load())).notebooks[0].pages[0].text, text);
  assert.deepEqual(report.crashes, []); assert.deepEqual(report.errors, []);
  report.phases.push('saved scene reopened');
  console.log('PASS: dois retângulos, flecha, texto gradual com acentos, gravação e reabertura sem queda; perfil isolado e rede bloqueada.');
})().catch(error => { report.failure = error.stack; console.error(error.stack); process.exitCode = 1; }).finally(async () => {
  if (app) await app.close().catch(() => {});
  fs.mkdirSync(path.dirname(reportFile), { recursive: true });
  fs.writeFileSync(reportFile, JSON.stringify(report, null, 2));
  const target = fs.realpathSync(profile), temporary = fs.realpathSync(os.tmpdir());
  if (path.dirname(target) === temporary && path.basename(target).startsWith('organon-board-spelling-')) fs.rmSync(target, { recursive: true, force: true });
});
